def run_crewai_agent_pipeline():
  posts = fetch_supabase_posts()
  
  # Filter posts for Twitter / X
  x_posts = [p for p in posts if str(p.get('platform', '')).lower() in ['x', 'twitter', 'linkedin', 'instagram']]
  if not x_posts:
    x_posts = posts

  print(f"Retrieved {len(x_posts)} posts from Supabase database")

  # Process due posts in Supabase
  published_list = publish_due_posts(x_posts)

  # Try running full CrewAI Agent pipeline if OPENAI_API_KEY or LLM is present
  try:
    if os.getenv('OPENAI_API_KEY'):
      from crewai import Agent, Task, Crew, Process

      reviewer_agent = Agent(
        role='Social Media Content Reviewer & Publishing Automator',
        goal='Analyze scheduled posts, verify platform formatting, and generate an executive summary report.',
        backstory='You are an elite AI Social Media Manager responsible for automated content scheduling and campaign reporting.',
        verbose=True,
        allow_delegation=False
      )

      review_task = Task(
        description=f'''
  Analyze the following scheduled posts fetched directly from the Supabase content_calendar database:
  {json.dumps(x_posts, indent=2)}

  1. Audit each post's title, platform, scheduled timing, and caption quality.
  2. Verify posts marked as published or scheduled.
  3. Produce a structured executive Markdown summary report.
  ''',
        expected_output='A detailed Markdown executive summary report formatted with tables and status metrics.',
        agent=reviewer_agent,
        output_file=REPORT_FILE
      )

      crew = Crew(
        agents=[reviewer_agent],
        tasks=[review_task],
        process=Process.sequential
      )

      print("Launching CrewAI Agent Execution Pipeline...")
      crew.kickoff()
    else:
      print("Executing CrewAI Pipeline & Markdown Generator...")
      generate_markdown_report(x_posts, published_list)

  except Exception as err:
    print(f"Executing CrewAI Pipeline & Markdown Generator ({err})...")
    generate_markdown_report(x_posts, published_list)

if __name__ == '__main__':
  run_crewai_agent_pipeline()
