def publish_due_posts(posts):
  """Update status of due posts to 'published' in Supabase"""
  published_ids = []
  for p in posts:
    if p.get('status') == 'scheduled':
      try:
        supabase.table('content_calendar').update({'status': 'published'}).eq('id', p['id']).execute()
        published_ids.append(p['id'])
      except Exception as e:
        print(f"Note updating post {p['id']}: {e}")
  return published_ids

